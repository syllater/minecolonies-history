#!/usr/bin/env python3
"""Build a deterministic, self-checking release-candidate bundle."""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE_FILES = (
    "README.md",
    "CHANGELOG.md",
    "COMPATIBILITY.md",
    "docs/RELEASE_CANDIDATE_NOTES.md",
    "docs/PLAYTEST_RELEASE_CHECKLIST.md",
)
FIXED_ZIP_TIME = (2024, 1, 1, 0, 0, 0)


def fail(message: str) -> None:
    print(f"RELEASE PACKAGE FAIL: {message}", file=sys.stderr)
    raise SystemExit(1)


def parse_properties(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def add_deterministic_file(archive: zipfile.ZipFile, source: Path, arcname: str) -> None:
    info = zipfile.ZipInfo(arcname, date_time=FIXED_ZIP_TIME)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o100644 << 16
    archive.writestr(info, source.read_bytes())


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument(
    "--manifest",
    type=Path,
    default=ROOT / "build/libs/SHA256SUMS.txt",
    help="verified SHA-256 manifest generated by CI",
)
parser.add_argument(
    "--output-dir",
    type=Path,
    default=ROOT / "build/release-package",
    help="directory for the candidate zip",
)
args = parser.parse_args()

props = parse_properties(ROOT / "gradle.properties")
version = props.get("mod_version", "")
if not re.fullmatch(r"\d+\.\d+\.\d+(?:-[0-9A-Za-z][0-9A-Za-z.-]*)?", version):
    fail(f"invalid mod version: {version!r}")
if not version.lower().endswith("rc1"):
    fail(f"expected an rc1 candidate version, found {version!r}")

build_libs = ROOT / "build/libs"
jars = sorted(
    path for path in build_libs.glob("*.jar")
    if not path.name.endswith(("-sources.jar", "-javadoc.jar", "-dev.jar"))
)
if len(jars) != 1:
    fail(f"expected exactly one distributable mod JAR in build/libs, found {len(jars)}")
jar = jars[0]
if version not in jar.name:
    fail(f"JAR filename {jar.name!r} does not contain configured version {version!r}")

manifest = args.manifest.resolve()
if not manifest.is_file():
    fail(f"checksum manifest not found: {manifest}")
manifest_record = None
for line in manifest.read_text(encoding="utf-8").splitlines():
    fields = line.strip().split(maxsplit=1)
    if len(fields) == 2 and Path(fields[1].lstrip("*")).name == jar.name:
        manifest_record = fields
        break
if manifest_record is None:
    fail(f"checksum manifest does not contain {jar.name}")
actual_digest = sha256(jar.read_bytes())
if manifest_record[0].lower() != actual_digest:
    fail(f"JAR checksum mismatch for {jar.name}")

for relative in PACKAGE_FILES:
    if not (ROOT / relative).is_file():
        fail(f"required release document not found: {relative}")

args.output_dir.mkdir(parents=True, exist_ok=True)
bundle_name = f"imperium-realms-{version}"
archive_path = args.output_dir / f"{bundle_name}.zip"
if archive_path.exists():
    archive_path.unlink()

archive_entries = [
    (jar, f"{bundle_name}/{jar.name}"),
    (manifest, f"{bundle_name}/SHA256SUMS.txt"),
    *((ROOT / relative, f"{bundle_name}/{Path(relative).name}") for relative in PACKAGE_FILES),
]

with zipfile.ZipFile(archive_path, mode="w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
    for source, arcname in archive_entries:
        add_deterministic_file(archive, source, arcname)

# Validate the archive itself before making it available as a build artifact.
with zipfile.ZipFile(archive_path, mode="r") as archive:
    bad_member = archive.testzip()
    if bad_member is not None:
        fail(f"ZIP integrity check failed at {bad_member}")
    bundled_jar = archive.read(f"{bundle_name}/{jar.name}")
    bundled_manifest = archive.read(f"{bundle_name}/SHA256SUMS.txt").decode("utf-8")
    expected_line = next(
        (
            line.strip().split(maxsplit=1)
            for line in bundled_manifest.splitlines()
            if len(line.strip().split(maxsplit=1)) == 2
            and Path(line.strip().split(maxsplit=1)[1].lstrip("*")).name == jar.name
        ),
        None,
    )
    if expected_line is None or expected_line[0].lower() != sha256(bundled_jar):
        fail("bundled JAR does not match its bundled SHA-256 manifest")
    bundled_names = set(archive.namelist())
    for _, arcname in archive_entries:
        if arcname not in bundled_names:
            fail(f"candidate bundle is missing {arcname}")

print(
    "RELEASE PACKAGE PASS: "
    f"{archive_path.relative_to(ROOT)} ({archive_path.stat().st_size} bytes), "
    f"JAR SHA-256 {actual_digest}"
)
